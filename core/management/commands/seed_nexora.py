class Command(BaseCommand):
    help = 'Добавить восемь демонстрационных публикаций Nexora без дубликатов'

    def handle(self, *args, **options):
        created_count = 0
        for item in POSTS:
            name = item['name']
            _, created = News.objects.get_or_create(name=name, defaults={key: value for key, value in item.items() if key != 'name'})
            if created:
                created_count += 1
        self.stdout.write(self.style.SUCCESS(f'Добавлено новых публикаций: {created_count}'))
